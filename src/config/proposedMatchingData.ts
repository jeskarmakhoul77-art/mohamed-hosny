export function getProposedMatchingStats() {
  let matchedCount = 0;
  let highConfidenceCount = 0;
  let mediumConfidenceCount = 0;
  let lowConfidenceCount = 0;
  let needsReviewCount = 0;
  let noSuitableImageCount = 0;
  let sharedCandidateCount = 0;

  const categoryBreakdown: Record<string, { total: number; matched: number; missing: number; labelAr: string; labelEn: string }> = {
    plumbing: { total: 5, matched: 0, missing: 0, labelAr: 'أعمال السباكة والصرف', labelEn: 'Plumbing Systems' },
    electrical: { total: 5, matched: 0, missing: 0, labelAr: 'التأسيسات الكهربائية', labelEn: 'Electrical Installations' },
    plastering: { total: 5, matched: 0, missing: 0, labelAr: 'المحارة ومعالجة الأسطح', labelEn: 'Plastering & Surface Prep' },
    ceramics: { total: 5, matched: 0, missing: 0, labelAr: 'السيراميك والبورسلين والرخام', labelEn: 'Ceramic & Tile' },
    gypsum: { total: 5, matched: 0, missing: 0, labelAr: 'الجبس بورد والأسقف المعلقة', labelEn: 'Gypsum Board & Ceilings' },
    painting: { total: 5, matched: 0, missing: 0, labelAr: 'الدهانات والتشطيبات الديكورية', labelEn: 'Painting & Decor' },
    interior: { total: 5, matched: 0, missing: 0, labelAr: 'التصميم الداخلي والفرش النهائي', labelEn: 'Interior & Joinery' },
    commercial: { total: 5, matched: 0, missing: 0, labelAr: 'المشاريع التجارية والمحلات والمكاتب', labelEn: 'Commercial Fit-Outs' }
  };

  PROPOSED_PORTFOLIO_MATCHES.forEach((match) => {
    if (match.candidateFileName) {
      matchedCount++;
      if (categoryBreakdown[match.categoryKey]) {
        categoryBreakdown[match.categoryKey].matched++;
      }
    } else {
      noSuitableImageCount++;
      if (categoryBreakdown[match.categoryKey]) {
        categoryBreakdown[match.categoryKey].missing++;
      }
    }

    if (match.confidence === 'high') highConfidenceCount++;
    if (match.confidence === 'medium') mediumConfidenceCount++;
    if (match.confidence === 'low') lowConfidenceCount++;

    if (match.reviewStatus === 'needs_review') needsReviewCount++;
    if (match.isSharedOrDuplicateCandidate) sharedCandidateCount++;
  });

  return {
    totalSlots: 40,
    matchedCount,
    unmatchedCount: noSuitableImageCount,
    highConfidenceCount,
    mediumConfidenceCount,
    lowConfidenceCount,
    needsReviewCount,
    sharedCandidateCount,
    categoryBreakdown: Object.entries(categoryBreakdown).map(([key, val]) => ({
      key,
      ...val
    }))
  };
}
